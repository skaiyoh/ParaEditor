import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import { stat } from 'node:fs/promises';

const entry = fileURLToPath(new URL('./tracking.entry.js', import.meta.url));
const output = fileURLToPath(new URL('./tracking.js', import.meta.url));

await build({
  entryPoints: [entry], outfile: output,
  bundle: true, format: 'esm', platform: 'browser', target: 'es2022',
  define: { NOISY_DEV: 'false' }, treeShaking: true, minify: true,
  legalComments: 'inline', charset: 'utf8',
  banner: { js: '// Generated by build_tracking.mjs from the existing calibrated camera/face foundations.' },
});
console.log(`Built tracking.js (${(await stat(output)).size} bytes); no new dependencies.`);
